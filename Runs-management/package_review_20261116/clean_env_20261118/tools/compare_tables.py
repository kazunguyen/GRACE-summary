"""Compare rebuilt tables with archived runs/tables/{tables_prereg,tables_corrected}: bytes, SHA-256, PNG pixels."""
import csv
import hashlib
import sys
from pathlib import Path

import numpy as np
from PIL import Image

arch, new, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
rows = []
for sub in ('tables_prereg', 'tables_corrected'):
    a_files = {p.relative_to(arch / sub).as_posix() for p in (arch / sub).rglob('*') if p.is_file()}
    n_files = {p.relative_to(new / sub).as_posix() for p in (new / sub).rglob('*') if p.is_file()}
    for rel in sorted(a_files | n_files):
        a, n = arch / sub / rel, new / sub / rel
        r = {'set': sub, 'file': rel, 'in_archive': a.exists(), 'in_rebuild': n.exists(),
             'archive_sha256': hashlib.sha256(a.read_bytes()).hexdigest() if a.exists() else '',
             'rebuild_sha256': hashlib.sha256(n.read_bytes()).hexdigest() if n.exists() else ''}
        r['byte_identical'] = bool(r['archive_sha256'] and r['archive_sha256'] == r['rebuild_sha256'])
        # README.md and *.log in the archive are run notes, not evaluator outputs
        r['archive_only_run_note'] = a.exists() and not n.exists() and (rel == 'README.md' or rel.endswith('.log'))
        r['pixel_identical'] = ''
        r['image_size'] = ''
        r['png_software_archive'] = r['png_software_rebuild'] = ''
        if rel.lower().endswith('.png') and a.exists() and n.exists():
            ia, ib = np.asarray(Image.open(a).convert('RGBA')), np.asarray(Image.open(n).convert('RGBA'))
            r['image_size'] = f'{ia.shape[1]}x{ia.shape[0]}'
            r['pixel_identical'] = ia.shape == ib.shape and bool((ia == ib).all())
            r['png_software_archive'] = Image.open(a).info.get('Software', '')
            r['png_software_rebuild'] = Image.open(n).info.get('Software', '')
        rows.append(r)
with open(out, 'w', encoding='utf-8', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)
for sub in ('tables_prereg', 'tables_corrected'):
    rs = [r for r in rows if r['set'] == sub]
    data = [r for r in rs if not r['file'].lower().endswith('.png')]
    png = [r for r in rs if r['file'].lower().endswith('.png')]
    print(f"{sub}: files={len(rs)} data byte-identical {sum(r['byte_identical'] for r in data)}/{len(data)}; "
          f"png byte-identical {sum(r['byte_identical'] for r in png)}/{len(png)}, pixel-identical {sum(r['pixel_identical'] is True for r in png)}/{len(png)}; "
          f"missing_in_rebuild={sum(not r['in_rebuild'] for r in rs)} extra_in_rebuild={sum(not r['in_archive'] for r in rs)}")
bad = [r for r in rows if not (r['byte_identical'] or r['pixel_identical'] is True or r['archive_only_run_note'])]
print('archive-only run notes (not generated by the evaluator):', sum(r['archive_only_run_note'] for r in rows))
for r in bad:
    print('DIFF', r['set'], r['file'])
sys.exit(1 if bad else 0)
